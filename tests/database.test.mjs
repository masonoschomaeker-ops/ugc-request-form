import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('submission and creator permissions are enforced by Postgres',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon; create role authenticated; create schema auth;
 create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema public,auth to anon,authenticated;
 grant execute on function auth.uid() to anon,authenticated;`);
 await db.exec(await readFile(new URL('../supabase/schema.sql',import.meta.url),'utf8'));
 const creator='11111111-1111-4111-8111-111111111111',other='22222222-2222-4222-8222-222222222222';
 await db.query('insert into auth.users values ($1),($2)',[creator,other]);
 await db.query('insert into private.ugc_creators values ($1)',[creator]);
 const payload={name:'Test',size:'Small',font:'Rounded',theme:'Yellow',contact:'test@example.test',payment:'Budget',ugc:'Pendant',necklace:'No',jumbo:'Yes',status:'Completed'};
 await db.exec('set role anon');
 const {rows:[{id}]}=await db.query('select public.submit_ugc_order($1::jsonb) as id',[JSON.stringify(payload)]);
 assert.match(id,/^[a-f0-9-]{36}$/);
 await assert.rejects(db.query('select * from public.ugc_orders'));
 await assert.rejects(db.query("update public.ugc_orders set status='Completed'"));
 await assert.rejects(db.query('insert into public.ugc_orders(data) values ($1::jsonb)',[JSON.stringify(payload)]));
 await assert.rejects(db.query('select public.submit_ugc_order($1::jsonb)',[JSON.stringify({...payload,contact:''})]));
 await assert.rejects(db.query('select public.submit_ugc_order($1::jsonb)',[JSON.stringify({...payload,notes:'a'.repeat(2001)})]));
 await db.exec('reset role; set role authenticated');
 await db.query("select set_config('request.jwt.claim.sub',$1,false)",[other]);
 assert.equal((await db.query('select * from public.ugc_orders')).rows.length,0);
 assert.equal((await db.query("update public.ugc_orders set status='Completed' returning id")).rows.length,0);
 await assert.rejects(db.query('select * from private.ugc_creators'));
 await db.query("select set_config('request.jwt.claim.sub',$1,false)",[creator]);
 let rows=(await db.query('select * from public.ugc_orders')).rows;
 assert.equal(rows.length,1);assert.equal(rows[0].status,'New');assert.equal(rows[0].data.jumbo,undefined);assert.equal(rows[0].data.status,undefined);
 await db.query("update public.ugc_orders set status='Reviewing' where id=$1",[id]);
 assert.equal((await db.query('select status from public.ugc_orders')).rows[0].status,'Reviewing');
 await assert.rejects(db.query("update public.ugc_orders set status='Anything'"));
 await assert.rejects(db.query("update public.ugc_orders set data='{}'::jsonb"));
 await db.close();
});
